package main

type seedCourse struct {
	Slug           string
	Title          string
	Description    string
	CEFRFrom       string
	CEFRTo         string
	EstimatedHours int
	Units          []seedUnit
}

type seedUnit struct {
	Position    int
	Title       string
	Description string
	Lessons     []seedLesson
}

type seedLesson struct {
	Position         int
	Title            string
	SkillFocus       string
	EstimatedMinutes int
	Activities       []seedActivity
}

type seedActivity struct {
	Position int
	Kind     string // vocab_multiple_choice, vocab_gap_fill, vocab_flashcard
	Config   map[string]any
	Body     map[string]any
}

type seedWordSense struct {
	Lemma        string
	POS          string
	CEFRLevel    string
	IPA          string
	Definition   string
	DefinitionVI string
	Examples     []seedExample
}

// seedExample is one example sentence and its Vietnamese rendering.
//
// The JSON tags are domain.ExampleSentence's, because that is what reads these
// rows back. The seed used to write a bare []string, and the mismatch was
// silent in the worst way: service.getWordSense unmarshals the column into
// []domain.ExampleSentence and discards the error, so every seeded word came
// back through the API with no examples at all, and `sentence_vi` — a field the
// schema, the domain type and the OpenAPI document all define — was never
// populated by anything.
//
// `audio_url` is deliberately absent rather than empty: the dictionary lookup
// fills it, and a seed that wrote "" would overwrite a real recording with a
// blank on the next run.
type seedExample struct {
	Sentence   string `json:"sentence"`
	SentenceVi string `json:"sentence_vi,omitempty"`
}

// ex pairs a sentence with its translation, so the data below reads as data.
func ex(sentence, vietnamese string) seedExample {
	return seedExample{Sentence: sentence, SentenceVi: vietnamese}
}

// The vocabulary the seed data is written in. They are constants because a
// string repeated forty times is a name waiting to be given, and because the
// config keys below are the contract the lesson runner reads.
const (
	skillVocabulary = "vocabulary"

	kindMultipleChoice = "vocab_multiple_choice"
	kindGapFill        = "vocab_gap_fill"
	kindFlashcard      = "vocab_flashcard"

	kindListenType    = "vocab_listen_type"
	kindMatch         = "vocab_match"
	kindReorder       = "vocab_reorder"
	kindContextChoice = "vocab_context_choice"

	cfgOptions         = "options"
	cfgOptionID        = "id"
	cfgOptionText      = "text"
	cfgCorrectOptionID = "correct_option_id"
	cfgSentenceBefore  = "sentence_before"
	cfgSentenceAfter   = "sentence_after"
	cfgExpectedAnswer  = "expected_answer"
	cfgTargetWord      = "target_word"
	cfgIPA             = "ipa"
	cfgDefinition      = "definition"
	// The Vietnamese gloss. The lesson runner already leads with the learner's
	// own language when the config carries one — it never did, so a Vietnamese
	// learner was handed an English definition of a word they do not know yet.
	cfgDefinitionVI    = "definition_vi"
	cfgExampleSentence = "example_sentence"

	// The full list the runner renders. `cfgExampleSentence` stays beside it
	// carrying the first one: it is the key the published activity config
	// examples show, and dropping it would break any client reading the old
	// name against content that has already been seeded.
	cfgExampleSentences = "example_sentences"

	// `vocab_listen_type`. The word the client speaks.
	//
	// It is the answer, and it reaches the browser: synthesis happens there, so
	// the text has to. That is a deliberate trade — the alternative is
	// server-side TTS, which means building platform/media — and it is why this
	// key is named for what it is rather than hidden among the other config. A
	// learner who opens the developer tools can read the word; grading still
	// happens on the server against the stored body, so nothing else is at
	// stake, and cheating here costs the learner the exercise and nobody else.
	cfgAudioText = "audio_text"
	// A definition shown beside the input, so a learner who cannot make out the
	// synthesised word is stuck on the spelling rather than on the meaning.
	cfgHint = "hint"

	// `vocab_match`. Two shuffled columns; the pairing is the answer and lives
	// in the body.
	cfgWords       = "words"
	cfgDefinitions = "definitions"

	// `vocab_reorder`. The sentence's words, shuffled.
	cfgTokens = "tokens"

	// `vocab_context_choice`. The sentence the learner reads the word in.
	cfgSentence = "sentence"

	// The lemmas an activity is about, so grading can schedule a review card
	// per word. Authored on the body, not the config: it is not rendered.
	bodyKeyWordLemmas = "word_lemmas"

	// The matching answer key, on the body and redacted before a learner sees
	// the activity.
	bodyKeyCorrectPairs = "correct_pairs"
)

// option builds one of the {id, text} rows the choice-based kinds render.
func option(id, text string) map[string]string {
	return map[string]string{cfgOptionID: id, cfgOptionText: text}
}

// acceptable is the authored list of answers a grader will accept. It exists so
// the data below reads as data rather than as a wall of []string{}.
func acceptable(values ...string) []string { return values }

