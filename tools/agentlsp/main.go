// agentlsp starts the gopls MCP server for AI coding agents (Claude Code, OpenCode, Cursor...)
// from a fresh clone, with nothing installed but Go:
//
//	go -C tools/agentlsp run . gopls
//
// Pinned tool versions are installed once into the user cache directory (not the repo).
// A repository with several go.mod files and no go.work gets a generated .gopls/go.work
// (git-ignored) that is used ONLY by gopls through GOWORK, so cross-module references work
// while every normal `go build` / `go test` keeps its per-module dependency versions.
package main

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

const (
	goplsPkg     = "golang.org/x/tools/gopls"
	goplsVersion = "v0.22.0"
)

func main() {
	if len(os.Args) < 2 {
		fail("usage: agentlsp gopls")
	}
	root, err := repoRoot()
	if err != nil {
		fail(err.Error())
	}
	switch os.Args[1] {
	case "gopls":
		runGopls(root)
	default:
		fail("unknown server " + os.Args[1])
	}
}

func runGopls(root string) {
	bin := install(goplsPkg, goplsVersion, "gopls")
	env := os.Environ()
	// Navigation does not need cgo; type-checking cgo packages (e.g. libde265 in ocr-service)
	// costs a lot of memory. AGENTLSP_CGO=1 restores the caller's setting.
	if os.Getenv("AGENTLSP_CGO") != "1" {
		env = setEnv(env, "CGO_ENABLED", "0")
	}
	if work, err := workspaceFile(root); err != nil {
		fail(err.Error())
	} else if work != "" {
		env = setEnv(env, "GOWORK", work)
	}
	run(root, env, bin, "mcp")
}

// workspaceFile returns "" when gopls needs no help: a single module or an existing go.work.
func workspaceFile(root string) (string, error) {
	if _, err := os.Stat(filepath.Join(root, "go.work")); err == nil {
		return "", nil
	}
	var mods []string
	maxGo := "1.21"
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "node_modules", "vendor", ".gopls", "tmp", "testdata":
				return filepath.SkipDir
			}
			// Developer tools are separate programs, not imported by services: leaving them
			// out keeps gopls memory down. AGENTLSP_ALL_MODULES=1 includes them.
			if rel, _ := filepath.Rel(root, path); filepath.ToSlash(rel) == "tools" && os.Getenv("AGENTLSP_ALL_MODULES") != "1" {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Name() != "go.mod" {
			return nil
		}
		dir := filepath.Dir(path)
		if filepath.Base(dir) == "agentlsp" {
			return nil
		}
		rel, _ := filepath.Rel(root, dir)
		mods = append(mods, filepath.ToSlash(rel))
		if v := goDirective(path); v != "" && versionLess(maxGo, v) {
			maxGo = v
		}
		return nil
	})
	if err != nil || len(mods) < 2 {
		return "", err
	}
	sort.Strings(mods)
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by tools/agentlsp for gopls only (GOWORK). Not used by go build/test.\ngo %s\n\nuse (\n", maxGo)
	for _, m := range mods {
		// Relative to .gopls/: absolute Windows paths are not matched against the module dirs.
		fmt.Fprintf(&b, "\t../%s\n", m)
	}
	b.WriteString(")\n")
	dir := filepath.Join(root, ".gopls")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	file := filepath.Join(dir, "go.work")
	if old, err := os.ReadFile(file); err != nil || string(old) != b.String() {
		if err := os.WriteFile(file, []byte(b.String()), 0o644); err != nil {
			return "", err
		}
	}
	return file, nil
}

func goDirective(gomod string) string {
	data, err := os.ReadFile(gomod)
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(data), "\n") {
		if fields := strings.Fields(line); len(fields) == 2 && fields[0] == "go" {
			return fields[1]
		}
	}
	return ""
}

func versionLess(a, b string) bool {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(pa) || i < len(pb); i++ {
		var x, y int
		if i < len(pa) {
			x, _ = strconv.Atoi(pa[i])
		}
		if i < len(pb) {
			y, _ = strconv.Atoi(pb[i])
		}
		if x != y {
			return x < y
		}
	}
	return false
}

// install puts pkg@version into <user cache>/agentlsp/<name>-<version>/ once and returns the binary.
func install(pkg, version, name string) string {
	cache, err := os.UserCacheDir()
	if err != nil {
		fail(err.Error())
	}
	dir := filepath.Join(cache, "agentlsp", name+"-"+version)
	bin := filepath.Join(dir, name)
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	if _, err := os.Stat(bin); err == nil {
		return bin
	}
	fmt.Fprintf(os.Stderr, "agentlsp: installing %s@%s (first run only)\n", pkg, version)
	cmd := exec.Command("go", "install", pkg+"@"+version)
	// Never let the repository's workspace or flags change how the pinned tool is built.
	cmd.Env = setEnv(setEnv(setEnv(os.Environ(), "GOBIN", dir), "GOWORK", "off"), "GOFLAGS", "")
	cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr // stdout is the MCP channel
	if err := cmd.Run(); err != nil {
		fail(fmt.Sprintf("go install %s@%s failed: %v", pkg, version, err))
	}
	return bin
}

func run(dir string, env []string, bin string, args ...string) {
	cmd := exec.Command(bin, args...)
	cmd.Dir, cmd.Env = dir, env
	cmd.Stdin, cmd.Stdout, cmd.Stderr = os.Stdin, os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			os.Exit(exit.ExitCode())
		}
		fail(err.Error())
	}
}

func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, ".git")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("agentlsp: not inside a git repository")
		}
		dir = parent
	}
}

func setEnv(env []string, key, value string) []string {
	prefix := key + "="
	out := env[:0:0]
	for _, kv := range env {
		if !strings.HasPrefix(strings.ToUpper(kv), strings.ToUpper(prefix)) {
			out = append(out, kv)
		}
	}
	return append(out, prefix+value)
}

func fail(msg string) {
	fmt.Fprintln(os.Stderr, "agentlsp:", msg)
	os.Exit(1)
}
